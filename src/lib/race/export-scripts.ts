import type { TestConfig } from "./types";

const AUTH_ENV_VAR = "TARGET_AUTH";

// Values that would leak credentials into a copied script.
const SECRET_HEADER_KEYS = new Set([
  "authorization",
  "cookie",
  "proxy-authorization",
  "x-api-key",
  "x-auth-token",
  "private-token",
]);

function shellSingleQuoted(value: string): string {
  return `'${value.replace(/'/g, `'\\''`)}'`;
}

type RequestArgs = { flags: string[]; needsAuthEnv: boolean };

/** Per-request curl flags derived from the config (headers + key mode). */
function requestArgs(config: TestConfig): RequestArgs {
  const flags: string[] = [];
  let needsAuthEnv = false;
  let hasContentType = false;

  for (const header of config.headers) {
    const key = header.key.trim();
    if (!key) continue;
    const lower = key.toLowerCase();
    if (lower === "content-type") hasContentType = true;
    // The Idempotency-Key toggle owns this header — never emit a stale row.
    if (lower === "idempotency-key") continue;
    if (SECRET_HEADER_KEYS.has(lower)) {
      flags.push(`-H "${key}: \${${AUTH_ENV_VAR}}"`);
      needsAuthEnv = true;
      continue;
    }
    flags.push(`-H ${shellSingleQuoted(`${key}: ${header.value}`)}`);
  }

  if (config.idempotency === "shared" && config.idempotencyKey?.trim()) {
    flags.push(`-H ${shellSingleQuoted(`Idempotency-Key: ${config.idempotencyKey.trim()}`)}`);
  }

  const hasBody = config.method !== "GET" && config.body.trim().length > 0;
  if (hasBody && !hasContentType) flags.push("-H 'Content-Type: application/json'");

  return { flags, needsAuthEnv };
}

/** The parallel burst loop as bash lines (shared by the script and CI exporters). */
function burstBashLines(config: TestConfig): string[] {
  const { flags } = requestArgs(config);
  const hasBody = config.method !== "GET" && config.body.trim().length > 0;

  const curlParts = [`curl -sS -o /dev/null -w "%{http_code} %{time_total}s\\n"`];
  if (config.method !== "GET") curlParts.push(`-X ${config.method}`);
  curlParts.push(`"$URL"`, ...flags);
  if (hasBody) curlParts.push(`--data ${shellSingleQuoted(config.body)}`);

  const curlCommand =
    curlParts.map((part, i) => (i === 0 ? `  ${part}` : `    ${part}`)).join(" \\\n") + " &";

  return [`for i in $(seq 1 ${config.concurrency}); do`, curlCommand, "done", "wait"];
}

/** Parallel bash cURL burst matching the configured endpoint, payload and burst size. */
export function buildCurlScript(config: TestConfig): string {
  const { needsAuthEnv } = requestArgs(config);
  const lines = [
    "#!/usr/bin/env bash",
    `# Burstproof burst test — ${config.concurrency} × ${config.method} ${config.url}`,
    "# Generated by Burstproof — https://burstproof-api-checker.lovable.app",
    "# Every request fires in parallel; each output line is '<status> <total-time>s'.",
    "set -euo pipefail",
    "",
    `URL=${shellSingleQuoted(config.url)}`,
  ];
  if (needsAuthEnv) {
    lines.push(
      "# A secret header value was redacted — export the real value before running:",
      `# export ${AUTH_ENV_VAR}='your-staging-token'`,
      `: "\${${AUTH_ENV_VAR}:?export ${AUTH_ENV_VAR} first (see comment above)}"`,
    );
  }
  lines.push("", ...burstBashLines(config));
  return lines.join("\n") + "\n";
}

/** Minimal GitHub Actions workflow wrapping the same burst as a manual job. */
export function buildCiWorkflow(config: TestConfig): string {
  const { needsAuthEnv } = requestArgs(config);
  const lines = [
    "# Burstproof — race-condition burst test",
    "# Trigger manually from the Actions tab, or wire it into a deploy pipeline.",
    "name: burstproof",
    "",
    "on:",
    "  workflow_dispatch:",
    "",
    "jobs:",
    "  burst:",
    "    runs-on: ubuntu-latest",
    "    steps:",
    `      - name: Burst ${config.concurrency} × ${config.method} ${config.url}`,
  ];
  if (needsAuthEnv) {
    lines.push("        env:", `          ${AUTH_ENV_VAR}: \${{ secrets.${AUTH_ENV_VAR} }}`);
  }
  lines.push("        run: |", ...burstBashLines(config).map((line) => `          ${line}`));
  return lines.join("\n") + "\n";
}
