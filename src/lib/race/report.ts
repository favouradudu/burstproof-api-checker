import type { BurstRequestResult, TestConfig, Verdict } from "./types";

const MAX_EXPORT_BODY = 2000;


// Headers can contain credentials — never export their values.
function redactConfig(config: TestConfig) {
  return {
    method: config.method,
    url: config.url,
    headerCount: config.headers.filter((h) => h.key.trim()).length,
    concurrency: config.concurrency,
    mode: config.mode,
    body: config.method === "GET" ? null : config.body,
  };
}

function resultRow(result: BurstRequestResult): string {
  const status = result.status ?? "ERR";
  const category =
    result.status === null
      ? "network error"
      : result.status < 300
        ? "success"
        : result.status === 409 || result.status === 429
          ? "conflict-handled"
          : result.status < 500
            ? "rejected"
            : "server error";
  const note = result.error ? ` — ${result.error}` : "";
  return `| ${result.index} | ${status} | ${result.durationMs}ms | ${category}${note} |`;
}

export function buildMarkdownReport(
  config: TestConfig,
  results: BurstRequestResult[],
  verdict: Verdict,
): string {
  const lines = [
    "# Race Condition Test Report",
    "",
    `Generated by [Idempotent](https://idempotent.dev) — concurrent double-submit stress test.`,
    "",
    "## Configuration",
    "",
    `- **Target:** \`${config.method} ${config.url}\``,
    `- **Burst size:** ${config.concurrency} simultaneous requests (Promise.all)`,
    `- **Dispatch:** ${config.mode === "proxy" ? "via server-side proxy (CORS-safe)" : "direct from browser"}`,
    `- **Request body:** ${config.method === "GET" ? "none (GET)" : "```json " + config.body.replace(/\s+/g, " ").slice(0, 120) + (config.body.length > 120 ? " …" : "") + " ```"}`,
    "",
    "## Verdict",
    "",
    `${verdict.emoji} **${verdict.headline}**`,
    "",
    verdict.summary,
    "",
    "## Requests",
    "",
    "| # | Status | Latency | Result |",
    "|---|--------|---------|--------|",
    ...results.map(resultRow),
    "",
    "## Analysis",
    "",
    ...verdict.reasons.map((r) => `- ${r}`),
    "",
    verdict.detail,
    "",
  ];
  if (verdict.uniqueIds.length > 0) {
    lines.push(
      "## Resource IDs observed",
      "",
      ...verdict.uniqueIds.map((id) => `- \`${id}\``),
      "",
    );
  }
  return lines.join("\n");
}

export function buildJsonReport(
  config: TestConfig,
  results: BurstRequestResult[],
  verdict: Verdict,
): string {
  return JSON.stringify(
    {
      tool: "Idempotent — race condition tester",
      generatedAt: new Date().toISOString(),
      config: redactConfig(config),
      verdict: {
        kind: verdict.kind,
        headline: verdict.headline,
        summary: verdict.summary,
        successes: verdict.successes,
        conflicts: verdict.conflicts,
        rejected: verdict.rejected,
        serverErrors: verdict.serverErrors,
        failed: verdict.failed,
        uniqueIds: verdict.uniqueIds,
        successSpreadMs: verdict.successSpreadMs,
        deduplicated: verdict.deduplicated,
      },
      requests: results.map((r) => ({
        index: r.index,
        dispatchAt: r.dispatchAt,
        receivedAt: r.receivedAt,
        durationMs: r.durationMs,
        status: r.status,
        error: r.error ?? null,
        responseBody: r.body.slice(0, MAX_EXPORT_BODY),
        viaProxy: r.viaProxy,
      })),
    },
    null,
    2,
  );
}

